#!/usr/bin/env python3
"""构建期加密产品 Key File,交付件只携带密文(license.key.enc)。

用法:
    python3 encrypt_key.py <key-file> <out.enc> <out-header.h>

密文格式(与 checker.c 的 decrypt_key_blob 配套):
    "WLC1"(4B magic) + nonce(8B,大端 64bit CTR 计数器起点) + XTEA-CTR 密文

对称密钥每次构建随机生成(16 字节),以 C 数组写入 <out-header.h> 编进
checker 二进制;产品 Key File 明文只存在于内部源码库,构建后不出现在
任何交付产物中,运行期解密只发生在 checker 内存里。
"""

import logging
import os
import struct
import sys
from pathlib import Path

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger("encrypt-key")

MAGIC = b"WLC1"
MASK = 0xFFFFFFFF
DELTA = 0x9E3779B9
ROUNDS = 32


def _be32(data: bytes) -> int:
    return struct.unpack(">I", data[:4])[0]


def _key_words(key: bytes):
    words = []
    for offset in range(0, 16, 4):
        words.append(struct.unpack(">I", key[offset : offset + 4])[0])  # noqa: E203 - PEP8 切片冒号惯例
    return words


def _xtea_encrypt_block(key_words, v0: int, v1: int):
    """XTEA 32 轮加密一个 64bit block,与 checker.c 的 xtea_encrypt_block 严格等价。"""
    s = 0
    for _ in range(ROUNDS):
        v0 = (v0 + (((((v1 << 4) & MASK) ^ (v1 >> 5)) + v1) ^ ((s + key_words[s & 3]) & MASK))) & MASK
        s = (s + DELTA) & MASK
        v1 = (v1 + (((((v0 << 4) & MASK) ^ (v0 >> 5)) + v0) ^ ((s + key_words[(s >> 11) & 3]) & MASK))) & MASK
    return v0, v1


def _keystream(key_words, nonce: bytes, length: int) -> bytes:
    hi = _be32(nonce[:4])
    lo = _be32(nonce[4:])
    out = bytearray()
    while len(out) < length:
        v0, v1 = _xtea_encrypt_block(key_words, hi, lo)
        out += struct.pack(">II", v0, v1)
        lo = (lo + 1) & MASK
        if lo == 0:
            hi = (hi + 1) & MASK
    return bytes(out[:length])


def encrypt(plaintext: bytes, key: bytes, nonce: bytes) -> bytes:
    """XTEA-CTR 加密(CTR 模式下加密与解密同一实现)。"""
    if len(key) != 16:
        raise ValueError("key must be 16 bytes")
    if len(nonce) != 8:
        raise ValueError("nonce must be 8 bytes")
    key_words = _key_words(key)
    stream = _keystream(key_words, nonce, len(plaintext))
    return MAGIC + nonce + bytes(a ^ b for a, b in zip(plaintext, stream))


def write_header(path: Path, key: bytes) -> None:
    """把对称密钥写成 C 数组头文件,由 build.sh 通过 -I 编进 checker。"""
    body = ", ".join(f"0x{byte:02X}" for byte in key)
    path.write_text(
        "/* Generated by encrypt_key.py at build time - never commit. */\n"
        f"static const unsigned char KEY_WRAP_KEY[16] = {{{body}}};\n",
        encoding="utf-8",
    )


def main(argv):
    if len(argv) != 4:
        logger.error("usage: encrypt_key.py <key-file> <out.enc> <out-header.h>")
        return 2
    key_file, enc_out, header_out = (Path(p) for p in argv[1:4])
    plaintext = key_file.read_bytes()
    key = os.urandom(16)
    nonce = os.urandom(8)
    enc_out.write_bytes(encrypt(plaintext, key, nonce))
    os.chmod(enc_out, 0o444)
    write_header(header_out, key)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
